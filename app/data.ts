export function getKeywordModifier(seedText: string) {
  let hash = 0;
  for (let i = 0; i < seedText.length; i++) {
    hash = seedText.charCodeAt(i) + ((hash << 5) - hash);
  }
  const index = Math.abs(hash) % KEYWORD_MODIFIERS.length;
  return KEYWORD_MODIFIERS[index];
}